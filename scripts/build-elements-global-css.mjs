#!/usr/bin/env node
// build-elements-global-css.mjs
//
// Writes the stylesheet @pitchfork-ui/elements ships for consumers: the design
// tokens followed by the `--pf-*` alias layer.
//
// Why generated rather than an @import: Stencil resolves `@import` in a global
// stylesheet with its own importer, before any PostCSS plugin runs, and that
// importer does not take bare package specifiers. theme.css begins with
// `@import '@pitchfork-ui/tokens/css'`, so pointing Stencil at it directly
// fails and no plugin ordering can rescue it. Concatenating leaves nothing to
// resolve.
//
// Why it has to exist at all: without the alias layer a consumer gets tokens
// but every `--pf-*` resolves to nothing — correct markup, unstyled
// components, no error. The React library ships the same two layers inside its
// styles.css.

import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const tokensCss = join(root, 'packages/tokens/dist/css/variables.css');
const themeCss = join(root, 'packages/react/src/styles/theme.css');
const outFile = join(root, 'packages/elements/src/global/pitchfork.css');

const tokens = readFileSync(tokensCss, 'utf8');
// Drop theme.css's own `@import` of the tokens: they are prepended here.
const theme = readFileSync(themeCss, 'utf8').replace(
  /^@import\s+['"]@pitchfork-ui\/tokens[^'"]*['"];\s*$/m,
  '',
);

mkdirSync(dirname(outFile), { recursive: true });
writeFileSync(
  outFile,
  [
    '/*',
    ' * Generated by scripts/build-elements-global-css.mjs — do not edit.',
    ' *',
    ' * packages/tokens/dist/css/variables.css + packages/react/src/styles/theme.css',
    ' */',
    '',
    tokens.trimEnd(),
    '',
    theme.trim(),
    '',
  ].join('\n'),
);

console.log(
  `elements global css: ${(tokens.length + theme.length / 1024).toFixed(0)} chars from tokens + theme`,
);

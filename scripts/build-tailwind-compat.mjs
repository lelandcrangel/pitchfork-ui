#!/usr/bin/env node
/**
 * Writes `packages/elements/dist/tailwind.css`, published as
 * `@pitchfork-ui/elements/tailwind.css`: the opt-in sheet that gives the
 * elements back the padding, borders and margins a CSS reset takes off them.
 *
 * Tailwind's preflight (and most resets) sets `margin: 0; padding: 0;
 * border: 0 solid` on `*`. That rule is in the page's stylesheet, and a page
 * rule beats a custom element's own `:host` rule whatever layer it is in,
 * because for normal declarations the outer cascade context wins over the
 * shadow tree's. So the half of the elements that draw their box on the host
 * -- pf-badge, pf-card, pf-option, pf-table-cell and the rest -- lose it in a
 * Tailwind app.
 *
 * The fix is `revert-layer` in Tailwind's own `base` layer, which rolls the
 * three properties back past preflight to what the shadow tree declares.
 * Measured in Chromium against a Tailwind 4 build: computed padding and
 * borders then equal a page without Tailwind, a `p-6` utility on the element
 * still wins, and the two obvious alternatives are wrong -- unlayered
 * `revert-layer` rolls back *to* preflight, and `revert` rolls back past every
 * author style, the shadow tree's included.
 *
 * The selector lists every pf-* tag rather than Stencil's `.hydrated`, which
 * every Stencil library on the page carries. The tags come from the
 * `@Component({ tag })` of each component folder, cross-checked against the
 * `docs.json` Stencil has just written, so a component cannot be added
 * without landing here. Listing all of them rather than the ones that draw a
 * box today is deliberate: on a host that declares none of the three, the
 * revert lands on the initial value, which is what it would have had anyway.
 *
 * Runs as the last step of the elements build, after `stencil build`, which
 * empties `dist`.
 */
import { existsSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const elementsRoot = resolve(dirname(fileURLToPath(import.meta.url)), '../packages/elements');
const componentsDir = join(elementsRoot, 'src/components');
const docsJson = join(elementsRoot, 'dist/docs.json');
const outFile = join(elementsRoot, 'dist/tailwind.css');

/** The tag each component folder declares in its `@Component` decorator. */
function sourceTags() {
  const tags = [];
  for (const entry of readdirSync(componentsDir, { withFileTypes: true })) {
    if (!entry.isDirectory()) continue;
    const folder = join(componentsDir, entry.name);
    const found = [];
    for (const file of readdirSync(folder)) {
      if (!file.endsWith('.tsx') || file.includes('.spec.')) continue;
      const source = readFileSync(join(folder, file), 'utf8');
      for (const match of source.matchAll(/@Component\(\{[^}]*?\btag:\s*['"]([^'"]+)['"]/g)) {
        found.push(match[1]);
      }
    }
    if (found.length === 0) {
      throw new Error(`build-tailwind-compat: ${entry.name} declares no @Component tag.`);
    }
    tags.push(...found);
  }
  return tags;
}

const tags = [...new Set(sourceTags())].sort();

const notPrefixed = tags.filter((tag) => !tag.startsWith('pf-'));
if (notPrefixed.length > 0) {
  throw new Error(`build-tailwind-compat: tags without the pf- prefix: ${notPrefixed.join(', ')}`);
}

// Stencil's own record of what it built. A tag in one list and not the other
// means the source scan above missed a component, or found one that is not
// built -- either way the sheet would be wrong, so refuse.
if (!existsSync(docsJson)) {
  throw new Error(`build-tailwind-compat: ${docsJson} is missing; run \`stencil build\` first.`);
}
const built = JSON.parse(readFileSync(docsJson, 'utf8')).components.map((c) => c.tag);
const missing = built.filter((tag) => !tags.includes(tag));
const extra = tags.filter((tag) => !built.includes(tag));
if (missing.length > 0 || extra.length > 0) {
  throw new Error(
    'build-tailwind-compat: the component folders and docs.json disagree. ' +
      `Built but not found in source: ${missing.join(', ') || 'none'}. ` +
      `Found in source but not built: ${extra.join(', ') || 'none'}.`,
  );
}

const css = `/*
 * @pitchfork-ui/elements/tailwind.css -- generated by
 * scripts/build-tailwind-compat.mjs. Do not edit.
 *
 * Import it alongside Tailwind, in either order:
 *
 *   @import 'tailwindcss';
 *   @import '@pitchfork-ui/elements/tailwind.css';
 *
 * Tailwind's preflight sets margin, padding and border to zero on every
 * element, and a page rule beats a custom element's own :host rule, so
 * elements that draw their box on the host lose it. revert-layer in the base
 * layer rolls those three properties back past preflight to what each
 * element declares. Utilities and your own unlayered CSS still win.
 */
@layer base {
${tags.map((tag) => `  ${tag}`).join(',\n')} {
    border: revert-layer;
    margin: revert-layer;
    padding: revert-layer;
  }
}
`;

writeFileSync(outFile, css);
console.log(`build-tailwind-compat: wrote dist/tailwind.css for ${tags.length} elements`);

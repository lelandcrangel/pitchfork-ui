import StyleDictionary from 'style-dictionary';

/**
 * The dark mode's values live on the tokens, not in `theme.css`.
 *
 * They used to be 32 hand-written `--color-semantic-*` lines inside
 * `theme.css`'s `[data-theme='dark']` block, which made the two modes of one
 * token two separate things: the light value in `src/tokens/color.json` and the
 * dark value in a stylesheet. A semantic colour could be added to one and
 * forgotten in the other, and one was — `border.disabled` never got a dark
 * value, so a disabled control border stayed at 14.48:1 on the dark background
 * while its enabled counterpart moved to 3.75:1.
 *
 * Each semantic colour now carries its dark value under
 * `$extensions['pitchfork.dark']`, and this format writes the CSS block out.
 * Two things make that worth the indirection:
 *
 *   - Style Dictionary resolves a reference inside `$extensions` to a literal
 *     (`{color.gray.900}` becomes `#0f172a`) while keeping the unresolved text
 *     on `token.original`. So the CSS can emit `var(--color-gray-900)`, exactly
 *     as the hand-written block did, and a Figma export can take the hex from
 *     the same token. One source, two shapes, nothing to keep in step.
 *   - `$description` takes the WCAG rationale that was in CSS comments, which
 *     puts it on the token rather than beside one of its two values — and a
 *     Figma variable has a description field for it to land in.
 *
 * `color-scheme: dark` and the `--pf-*` component overrides stay hand-written
 * in `theme.css`: they are not tokens, and a component alias has no business in
 * a design-token file.
 */
const DARK_KEY = 'pitchfork.dark';

const isDarkCapable = (token) => Boolean(token.$extensions?.[DARK_KEY]);

StyleDictionary.registerFormat({
  name: 'css/dark-semantic',
  format: ({ dictionary }) => {
    // `{color.gray.500}` has to become `var(--color-gray-500)`, and the name a
    // token ends up with is not its path with dots swapped for dashes: the
    // kebab transform splits camelCase too, so `action.primaryHover` becomes
    // `action-primary-hover`. Ask the dictionary rather than reimplement it.
    //
    // The dark tokens are selected here rather than with the file's `filter`,
    // because a filter narrows `allTokens` itself: the primitives a dark value
    // references would be gone from the very map used to resolve them.
    const nameByPath = new Map(dictionary.allTokens.map((t) => [t.path.join('.'), t.name]));

    const lines = [];
    for (const token of dictionary.allTokens) {
      if (!isDarkCapable(token)) continue;

      const reference = token.original?.$extensions?.[DARK_KEY] ?? '';
      const path = reference.replace(/^\{|\}$/g, '');
      const referenced = nameByPath.get(path);
      if (!referenced) {
        throw new Error(
          `${token.name}: its ${DARK_KEY} value ${reference} is not a token in this dictionary. ` +
            'A dark value must reference a primitive, so that both modes move together.',
        );
      }

      if (token.$description) {
        lines.push('', `  /* ${token.$description} */`);
      }
      lines.push(`  --${token.name}: var(--${referenced});`);
    }

    if (lines.length === 0) {
      throw new Error(
        `No token carries a ${DARK_KEY} value, so this file would define no dark mode at all. ` +
          'That is a build producing an empty stylesheet, not a theme with no overrides.',
      );
    }

    return [
      '/*',
      ' * GENERATED by style-dictionary — do not edit.',
      ' *',
      " * The dark mode's semantic colours, from $extensions['pitchfork.dark'] in",
      ' * src/tokens/color.json. `color-scheme` and the --pf-* component overrides',
      " * are hand-written in theme.css's own [data-theme='dark'] block.",
      ' */',
      '',
      "[data-theme='dark'] {",
      ...lines.slice(lines[0] === '' ? 1 : 0),
      '}',
      '',
    ].join('\n');
  },
});

export default {
  source: ['src/tokens/**/*.json'],
  platforms: {
    css: {
      transformGroup: 'css',
      buildPath: 'dist/css/',
      files: [
        {
          destination: 'variables.css',
          format: 'css/variables',
          options: {
            selector: ':root',
            outputReferences: true,
          },
        },
        {
          destination: 'dark-semantic.css',
          format: 'css/dark-semantic',
        },
      ],
    },
    json: {
      transformGroup: 'js',
      buildPath: 'dist/json/',
      files: [
        {
          destination: 'tokens.json',
          format: 'json/nested',
        },
      ],
    },
  },
};
